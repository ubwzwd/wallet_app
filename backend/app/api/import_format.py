"""The standard import format, served publicly (05-import-and-llm.md §5.5, 04 §3.3).

No auth, no database: the body is the 11-column contract plus the skill texts
that live in ``skills/wallet-import/`` (decision §6 — the skill is a repo
deliverable, generated by ``scripts/gen_import_skill.py`` from
``core/categories.py``, so this endpoint and the skill never drift apart).

The three skill-derived strings (``sample_csv``, ``skill_text``,
``skill_markdown``) are read from disk once, at process start, and cached in
memory for the rest of the process's life — same shape as ``categories.py``'s
``_body()`` cache. If a deliverable is missing (a broken build, a repo
checkout that skipped ``skills/``), the endpoint must not take the whole app
down with it: a missing file degrades to an empty string plus a logged
error, rather than raising at import time or on every request.

Where the deliverables come from in production: the API image is built from
the repo root and lays the two trees out side by side — ``backend/`` becomes
``/app`` and ``skills/`` becomes ``/app/skills`` (infra/Dockerfile.api). So
inside the image this module sits at ``/app/app/api/`` and the candidate that
resolves is the *second* one, ``<backend dir>/skills/wallet-import`` =
``/app/skills/wallet-import``; ``<repo-root>`` is ``/`` there and holds
nothing. In a checkout (and local dev) the *first* candidate resolves. Both
are load-bearing — neither is dead code. A missing file still degrades to an
empty string plus a logged ``error`` (not a ``warning``) on process start:
an import-guide page (04 §4.10 step 0's only data source) that renders blank
must show up in ops rather than take the app down or fail silently.

Caching: unlike ``GET /categories`` this is *not* ``immutable`` — its
``version`` changes on ordinary deploys (whenever ``CATEGORY_VERSION``
bumps), not only on a breaking format change, so a client that cached it
forever could hand the user a stale skill text well past its expiry. 03
§5.7's own example prescribes ``public, max-age=86400`` (one day) plus an
``ETag``; that is short enough to bound staleness to about a day while still
saving a full re-fetch on every guide-page visit within that window, and the
``ETag`` makes a same-day revisit after a same-day deploy a cheap 304
instead of a stale hit. The tag is a digest of the whole body, not just
``CATEGORY_VERSION``: the three skill texts are re-generated on ordinary
deploys and a release that only rewords them leaves the version untouched,
so a version-only tag would answer every one of those cached clients 304
for as long as they keep revalidating — precisely the staleness §5.7 is
worried about.
"""
