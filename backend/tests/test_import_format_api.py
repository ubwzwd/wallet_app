def test_the_example_csv_passes_the_real_validator_cleanly():
    """``skills/wallet-import/example.csv`` is what the guide page shows and what
    every model is shown as the target shape, so it has to survive the importer's
    own rules untouched: right version line, right header, and not one row that
    needs a ``hint`` or earns a ``flag`` (05 §2.2-§2.4). A regenerated skill whose
    example drifts out of the format would teach every user a file the uploader
    then rejects.
    """
    ctx = ImportContext(
        ledger_id=uuid.uuid4(),
        source_id=uuid.uuid4(),
        source_currency="CNY",  # the example's rows are all CNY
        source_type="credit",  # ... including a `repayment` transfer leg
        base_currency="CNY",
        actor_id=uuid.uuid4(),
        category_version=CATEGORY_VERSION,
    )

    raw = read_upload(EXAMPLE_CSV_PATH.read_bytes(), "example.csv")
    check_shape(raw)
    assert check_version(raw, CATEGORY_VERSION) == CATEGORY_VERSION
    rows = normalize_rows(raw, ctx)

    assert [row.row_no for row in rows] == list(range(1, 8))  # 7 data rows
    assert [row.hint for row in rows] == [None] * len(rows)
    assert [sorted(row.flags) for row in rows] == [[] for _ in rows]


