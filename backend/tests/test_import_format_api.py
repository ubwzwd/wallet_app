"""Tests for ``GET /import-format`` (05-import-and-llm.md §5.5, 04 §3.3).

Public, identity-free: the body is the 11-column contract plus the skill
texts that live in ``skills/wallet-import/``, generated by
``scripts/gen_import_skill.py`` from ``core/categories.py`` (decision §6).
"""
import pathlib

import pytest

from app.core.categories import CATEGORY_VERSION

IMPORT_FORMAT_URL = "/api/v1/import-format"

EXPECTED_HEADERS = [
    "date",
    "amount",
    "currency",
    "kind",
    "transfer_role",
    "transfer_subtype",
    "merchant",
    "note",
    "category_l1",
    "category_l2",
    "source_ref",
]

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
EXAMPLE_CSV_PATH = REPO_ROOT / "skills" / "wallet-import" / "example.csv"
SKILL_MD_PATH = REPO_ROOT / "skills" / "wallet-import" / "SKILL.md"
CHATGPT_INSTRUCTIONS_PATH = REPO_ROOT / "skills" / "wallet-import" / "chatgpt-instructions.md"

ETAG = f'"{CATEGORY_VERSION}"'


@pytest.fixture()
def body(client):
    """The parsed ``GET /import-format`` body, fetched with no auth headers at all."""
    response = client.get(IMPORT_FORMAT_URL)
    assert response.status_code == 200
    return response.json()


# ---------------------------------------------------------------------------
# Anonymous access
# ---------------------------------------------------------------------------


def test_anonymous_client_gets_200(client):
    """No Authorization header, no auth-related dependency — must not be gated."""
    response = client.get(IMPORT_FORMAT_URL)
    assert response.status_code == 200


def test_invalid_bearer_token_is_still_ignored(client):
    """Even a garbage token must not turn this into a 401 — the endpoint takes no auth at all."""
    response = client.get(IMPORT_FORMAT_URL, headers={"Authorization": "Bearer not-a-real-token"})
    assert response.status_code == 200


# ---------------------------------------------------------------------------
# Shape (04-frontend.md §3.3 ImportFormat)
# ---------------------------------------------------------------------------


def test_version_matches_category_version(body):
    assert body["version"] == CATEGORY_VERSION


def test_headers_are_the_fixed_11_columns_in_order(body):
    assert body["headers"] == EXPECTED_HEADERS
    assert len(body["headers"]) == 11


def test_columns_cover_all_11_headers_in_the_same_order(body):
    names = [c["name"] for c in body["columns"]]
    assert names == EXPECTED_HEADERS


def test_each_column_has_required_desc_zh_desc_en(body):
    for column in body["columns"]:
        assert isinstance(column["required"], bool)
        assert column["desc_zh"], f"{column['name']} missing desc_zh"
        assert column["desc_en"], f"{column['name']} missing desc_en"


def test_required_columns_match_the_spec(body):
    required = {c["name"]: c["required"] for c in body["columns"]}
    assert required["date"] is True
    assert required["amount"] is True
    assert required["currency"] is True
    assert required["kind"] is True
    assert required["transfer_role"] is False
    assert required["merchant"] is False
    assert required["source_ref"] is False


def test_instructions_present_in_both_languages(body):
    assert body["instructions_zh"].strip()
    assert body["instructions_en"].strip()
    assert body["instructions_zh"] != body["instructions_en"]


# ---------------------------------------------------------------------------
# Skill deliverables come straight from skills/wallet-import/ (decision §6)
# ---------------------------------------------------------------------------


def test_sample_csv_is_verbatim_the_repo_example_file(body):
    on_disk = EXAMPLE_CSV_PATH.read_text(encoding="utf-8")
    assert body["sample_csv"] == on_disk


def test_sample_csv_starts_with_the_current_version_line(body):
    assert body["sample_csv"].startswith(f"# version: {CATEGORY_VERSION}")


def test_skill_markdown_is_verbatim_skill_md_and_contains_a_category_code(body):
    on_disk = SKILL_MD_PATH.read_text(encoding="utf-8")
    assert body["skill_markdown"] == on_disk
    assert body["skill_markdown"].strip() != ""
    # `groceries` is an l1 code from core/categories.py; its presence proves the
    # category table was actually rendered into the skill text, not just a stub.
    assert "`groceries`" in body["skill_markdown"]


def test_skill_text_is_verbatim_chatgpt_instructions_and_non_empty(body):
    on_disk = CHATGPT_INSTRUCTIONS_PATH.read_text(encoding="utf-8")
    assert body["skill_text"] == on_disk
    assert body["skill_text"].strip() != ""


# ---------------------------------------------------------------------------
# Caching
# ---------------------------------------------------------------------------


def test_cache_control_and_etag_present(client):
    response = client.get(IMPORT_FORMAT_URL)
    assert response.headers["ETag"] == ETAG
    assert "max-age" in response.headers["Cache-Control"]


def test_matching_if_none_match_returns_304(client):
    response = client.get(IMPORT_FORMAT_URL, headers={"If-None-Match": ETAG})
    assert response.status_code == 304


def test_stale_if_none_match_returns_200(client):
    response = client.get(IMPORT_FORMAT_URL, headers={"If-None-Match": '"some-old-version"'})
    assert response.status_code == 200


# ---------------------------------------------------------------------------
# No side effects
# ---------------------------------------------------------------------------


def test_response_carries_no_ledger_or_user_fields(body):
    """A public, identity-free endpoint (decision §6, §11) must not leak account data."""
    forbidden_keys = {"ledger_id", "user_id", "source_id", "created_by"}
    assert forbidden_keys.isdisjoint(body.keys())
